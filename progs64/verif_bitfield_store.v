  rewrite Int.bits_bitfield_insert by (change Int.zwordsize with 32; lia).
  destruct (zle 3 i); [|lia]. destruct (zlt i (3+3)); [lia|]. cbn.
  rewrite Int.bits_zero_ext by lia. rewrite zlt_true by lia.
  rewrite Int.bits_bitfield_insert by (change Int.zwordsize with 32; lia).
  destruct (zle 0 i); [|lia]. destruct (zlt i (0+3)); [lia|]. reflexivity.
Qed.


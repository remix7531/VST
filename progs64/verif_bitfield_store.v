  change (Int.testbit (Int.zero_ext 8 (Int.bitfield_insert 3 3
    (Int.zero_ext 8 (Int.bitfield_insert 0 3 carrier (Int.repr 1))) (Int.repr 2))) i =
    Int.testbit carrier i).

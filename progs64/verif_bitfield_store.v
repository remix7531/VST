Lemma sequential_byte_writes_preserve_neighboring_bits: forall carrier i,
  6 <= i < 8 ->
  Int.testbit (bitfield_updated_integer I8 3 3
    (bitfield_updated_integer I8 0 3 carrier (Int.repr 1)) (Int.repr 2)) i =
  Int.testbit carrier i.
